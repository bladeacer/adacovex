#!/usr/bin/env python3
"""Generate the AGENTS.md documentation tree.

Renders the hand-written documentation as an ASCII tree, one line per page
with the page's H1 title, so an agent can see how the manual is organised
and update the right page when a feature changes.  The generated reference
trees (`docs/api-docs/` and `docs/changelogs/`) are shown as directories
with a note instead of one line per file: they are produced by a tool or a
release, not edited by hand.

The tree is written between the `<!-- docs-tree:begin -->` and
`<!-- docs-tree:end -->` markers in AGENTS.md.

Usage:
  python3 tools/gen-docs-tree.py [--dry-run] [--check]

--dry-run  Print the would-be tree without editing AGENTS.md.
--check    Verify AGENTS.md already carries the current tree; exit 1 on
           drift (the `docs tree` gate) without editing.

Exit code 0 when every page has a title and AGENTS.md is current (or, with
--dry-run/--check, would be / already is), 1 otherwise.
"""

import argparse
import sys
from pathlib import Path
from typing import Dict, List, Tuple

ROOT: Path = Path(__file__).resolve().parent.parent
DOCS: Path = ROOT / "docs"
AGENTS: Path = ROOT / "AGENTS.md"

BEGIN_MARKER: str = "<!-- docs-tree:begin -->"
END_MARKER: str = "<!-- docs-tree:end -->"

#  Directories whose pages are generated, so the tree names the directory
#  and its producer rather than listing every page.
GENERATED_DIRS: Dict[str, str] = {
    "api-docs": "generated by `just doc`; edit the Ada docstrings, never these pages",
    "changelogs": "one page per release; `just release` adds the current one",
}

#  The order a reader meets the manual in.  A directory not named here is
#  appended alphabetically, so a new section is never hidden.
DIR_ORDER: List[str] = [
    "usage",
    "contributing",
    "proof",
    "compliance",
    "badges",
]

#  Project-root files that belong to the manual picture even though they sit
#  above docs/.
ROOT_PAGES: List[str] = ["README.md", "CONTRIBUTING.md"]

#  Generated pages that are not part of the manual's navigation: the native
#  test report is rewritten by `just test` and has no prose title.
GENERATED_FILES: List[str] = ["docs/test_result.md"]


def title_of(page: Path) -> str:
    """The page's H1 text, or an empty string when it has none.

    Badges and images may precede the heading, as they do in README.md, so
    the whole file is searched for the first `# ` line rather than only its
    opening line.
    """
    for raw in page.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line.startswith("# "):
            return line[2:].strip()
    return ""


def collect() -> Tuple[Dict[str, List[Tuple[str, str]]], List[str]]:
    """Return (files by directory, pages missing an H1).

    Keys are POSIX directory paths relative to the project root ("" for
    project-root pages, "docs", "docs/usage", ...).
    """
    files: Dict[str, List[Tuple[str, str]]] = {}
    untitled: List[str] = []

    #  Generated trees are present in the manual even though their pages are
    #  not listed one by one.
    for name in GENERATED_DIRS:
        files.setdefault(f"docs/{name}", [])

    for rel in ROOT_PAGES:
        page = ROOT / rel
        if not page.is_file():
            continue
        title = title_of(page)
        if not title:
            untitled.append(rel)
        files.setdefault("", []).append((page.name, title))

    for page in sorted(DOCS.rglob("*.md")):
        rel = page.relative_to(ROOT).as_posix()
        parts = page.relative_to(DOCS).parts
        if rel in GENERATED_FILES:
            continue
        if len(parts) > 1 and parts[0] in GENERATED_DIRS:
            continue
        title = title_of(page)
        if not title:
            untitled.append(rel)
        parent = page.parent.relative_to(ROOT).as_posix()
        files.setdefault(parent, []).append((page.name, title))

    return files, untitled


def render(files: Dict[str, List[Tuple[str, str]]]) -> List[str]:
    lines: List[str] = [BEGIN_MARKER]
    lines.append("<!-- Generated by `just docs-tree`; do not edit by hand. -->")
    lines.append("")

    def render_dir(dir_rel: str, prefix: str) -> None:
        entries = sorted(files.get(dir_rel, []), key=lambda e: e[0])
        candidates = [
            d for d in files
            if d != dir_rel
            and (d.startswith(dir_rel + "/") if dir_rel else True)
            and d.count("/") == (dir_rel.count("/") + 1 if dir_rel else 0)
        ]
        order = {name: index for index, name in enumerate(DIR_ORDER)}
        subdirs = sorted(
            candidates,
            key=lambda d: (order.get(d.rsplit("/", 1)[-1], len(order)),
                           d.rsplit("/", 1)[-1]),
        )
        children: List[Tuple[str, str, str]] = []
        for name, title in entries:
            children.append(("file", name, title))
        for sub in subdirs:
            children.append(("dir", sub.rsplit("/", 1)[-1], sub))
        for index, (kind, name, payload) in enumerate(children):
            last = index == len(children) - 1
            connector = "`-- " if last else "|-- "
            if kind == "file":
                lines.append(f"{prefix}{connector}{name} -- {payload}")
            else:
                label = name
                note = GENERATED_DIRS.get(name)
                if note:
                    label += f"/ ({note})"
                else:
                    label += "/"
                lines.append(f"{prefix}{connector}{label}")
                if not note:
                    child_prefix = prefix + ("    " if last else "|   ")
                    render_dir(payload, child_prefix)

    lines.append("docs/")
    render_dir("docs", "")
    lines.append("")
    lines.append(END_MARKER)
    return lines


def main(argv: List[str]) -> int:
    ap: argparse.ArgumentParser = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry-run", action="store_true",
                    help="print the would-be tree without editing AGENTS.md")
    ap.add_argument("--check", action="store_true",
                    help="verify AGENTS.md already matches; exit 1 on drift")
    args: argparse.Namespace = ap.parse_args(argv)

    files, untitled = collect()
    if untitled:
        for rel in untitled:
            print(f"  MISSING TITLE: {rel} (add a `# Title` heading)",
                  file=sys.stderr)
        return 1

    block: str = "\n".join(render(files))
    if args.dry_run:
        print(block)
        return 0

    text: str = AGENTS.read_text(encoding="utf-8")
    if BEGIN_MARKER not in text or END_MARKER not in text:
        print(f"error: AGENTS.md is missing the docs-tree markers "
              f"{BEGIN_MARKER!r} / {END_MARKER!r}", file=sys.stderr)
        return 1

    start: int = text.index(BEGIN_MARKER)
    end: int = text.index(END_MARKER) + len(END_MARKER)
    current: str = text[start:end]
    if args.check:
        if current == block:
            print("ok: AGENTS.md documentation tree is current")
            return 0
        print("error: AGENTS.md documentation tree is out of date "
              "(run `just docs-tree`)", file=sys.stderr)
        return 1
    if current != block:
        AGENTS.write_text(text[:start] + block + text[end:],
                          encoding="utf-8", newline="\n")
    print("AGENTS.md documentation tree regenerated.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

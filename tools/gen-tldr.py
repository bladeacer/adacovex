#!/usr/bin/env python3
"""Generate src/adacovex-tldr_template.ads from docs/tldr/adacovex.md.

The tldr page is authored once, in the tldr-pages repository format
(`docs/tldr/adacovex.md`), and that file is the single source.  `adacovex
tldr` installs the page into a local tldr client without a network, so the
page text is bundled into the binary the same way the dashboard template
and the offline manual are: this script turns the Markdown page into one
Ada String constant, and the generated spec is committed.

The page has to stay pure ASCII (`just ascii-check`), so the generator
rejects any non-ASCII byte instead of encoding it silently.

Ada string literals cannot span lines, so each page line is emitted as
short quoted chunks joined with ` & ASCII.LF & `.  Embedded double quotes
are doubled per Ada syntax.

Usage:
  python3 tools/gen-tldr.py [--check] [--page=PATH] [--out=PATH]

--check   Verify the generated file matches docs/tldr/adacovex.md; exit 1
          on mismatch (used by `just tldr-check` so the bundled page can
          never drift from the authored one).
--page    Page source path (default: docs/tldr/adacovex.md).
--out     Output Ada spec path (default: src/adacovex-tldr_template.ads).

Exit code 0 on success, 1 on a missing source, a non-ASCII source, or a
--check mismatch.
"""

import argparse
import sys
from pathlib import Path
from typing import List

ROOT: Path = Path(__file__).resolve().parent.parent

CHUNK_MAX: int = 60

HEADER: str = (
    "--  Generated by tools/gen-tldr.py from docs/tldr/adacovex.md -- the\n"
    "--  bundled tldr page that `adacovex tldr` installs into a local tldr\n"
    "--  client (tealdeer custom pages, or a base client's cache pages tree).\n"
    "--  Edit docs/tldr/adacovex.md and run `just build` (or `just\n"
    "--  tldr-check` to verify); do not edit this file by hand.\n"
)

TAIL: str = (
    "\n"
    "end Adacovex.Tldr_Template;\n"
)


def render(page: str) -> str:
    """Return the Ada spec embedding *page* as one String constant."""
    chunks: List[str] = []
    breaks: int = page.count("\n")
    for i, line in enumerate(page.split("\n")):
        for start in range(0, len(line), CHUNK_MAX):
            piece: str = line[start : start + CHUNK_MAX].replace('"', '""')
            chunks.append('"' + piece + '"')
        if i < breaks:
            chunks.append("ASCII.LF")
    body: str = "\n  & ".join(chunks)
    if body == "":
        # An empty page still needs a legal constant; it can never match a
        # client page, so the case is a loud authoring bug rather than a
        # silently empty install.
        raise ValueError("the tldr page is empty")
    return (
        HEADER
        + "package Adacovex.Tldr_Template is\n"
        + "\n"
        + "   --  The tldr page text (docs/tldr/adacovex.md), byte for byte.\n"
        + "   Page : constant String :=\n"
        + body
        + ";\n"
        + TAIL
    )


def generate(out: Path, page_path: Path) -> bool:
    """Write the Ada spec; return True only when its content changed.

    A byte-identical rewrite would bump the file's mtime and make the GNAT
    incremental build recompile the generated unit and its dependants on
    every `just build` / `just prove`.
    """
    page: str = page_path.read_text(encoding="ascii")
    content: str = render(page)
    if out.is_file() and out.read_text(encoding="ascii") == content:
        return False
    out.write_text(content, encoding="ascii", newline="\n")
    return True


def parse_args(argv: List[str]) -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description="Bundle docs/tldr/adacovex.md into an Ada string constant."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed generated file matches the page",
    )
    parser.add_argument(
        "--page",
        default=str(ROOT / "docs" / "tldr" / "adacovex.md"),
        help="page source path (default: docs/tldr/adacovex.md)",
    )
    parser.add_argument(
        "--out",
        default=str(ROOT / "src" / "adacovex-tldr_template.ads"),
        help="output Ada spec path (default: src/adacovex-tldr_template.ads)",
    )
    return parser.parse_args(argv)


def main(argv: List[str]) -> int:
    """Run the generator; return the process exit code."""
    args = parse_args(argv)
    page_path: Path = Path(args.page).resolve()
    out: Path = Path(args.out).resolve()
    if not page_path.is_file():
        print(f"error: page not found: {page_path}", file=sys.stderr)
        return 1
    try:
        if args.check:
            before: str = out.read_text(encoding="ascii") if out.is_file() else ""
            generate(out, page_path)
            after: str = out.read_text(encoding="ascii")
            if before != after:
                print(
                    f"error: {out.name} is stale -- run tools/gen-tldr.py "
                    "(or just build) and commit the regenerated file.",
                    file=sys.stderr,
                )
                return 1
            print(f"{out.name} is up to date.")
            return 0
        changed: bool = generate(out, page_path)
        print(f"{out.name} {'regenerated' if changed else 'up to date'}.")
        return 0
    except (UnicodeDecodeError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
